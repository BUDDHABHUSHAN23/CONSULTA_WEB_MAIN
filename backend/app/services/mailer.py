# ---- Mailer health + test ----
async def check_mailer(timeout: float = 10.0) -> dict:
    """Connect, (optionally) login, NOOP. Treat 503 'previously authenticated' as healthy."""
    tls_mode = "implicit_tls" if SMTP_PORT == 465 else ("starttls" if SMTP_PORT in (25, 587) else "plain")
    started = time.perf_counter()
    client = aiosmtplib.SMTP(
        hostname=SMTP_HOST,
        port=SMTP_PORT,
        username=SMTP_USER,
        password=SMTP_PASS,
        timeout=timeout,
        **_tls_kwargs(SMTP_PORT),
    )
    try:
        await client.connect()
        already_authed = False
        try:
            if SMTP_USER and SMTP_PASS:
                await client.login(SMTP_USER, SMTP_PASS)
        except SMTPAuthenticationError as e:
            msg = (str(e) or "").lower()
            if getattr(e, "code", None) == 503 or "previously authenticated" in msg:
                already_authed = True
            else:
                raise
        code, resp = await client.noop()
        ok = 200 <= int(code) < 400
        return {
            "ok": bool(ok),
            "host": SMTP_HOST,
            "port": SMTP_PORT,
            "tls": tls_mode,
            "auth": bool(SMTP_USER and SMTP_PASS),
            "already_authed": already_authed,
            "code": int(code),
            "response": resp.decode() if isinstance(resp, (bytes, bytearray)) else str(resp),
            "latency_ms": round((time.perf_counter() - started) * 1000),
        }
    except Exception as e:
        return {
            "ok": False,
            "host": SMTP_HOST,
            "port": SMTP_PORT,
            "tls": tls_mode,
            "auth": bool(SMTP_USER and SMTP_PASS),
            "error": repr(e),
            "latency_ms": round((time.perf_counter() - started) * 1000),
        }
    finally:
        try:
            await client.quit()
        except Exception:
            pass

async def send_test_email(to: Optional[Iterable[str]] = None, subject_prefix: str = "[Mailer Test] ") -> dict:
    """Send a short test message to given recipients (or NOTIFY_TO/SMTP_USER fallback), then return live status."""
    recipients = _normalize(to or (NOTIFY_TO or ([SMTP_USER] if SMTP_USER else [])))
    if not recipients:
        return {"ok": False, "error": "No recipients configured"}
    html_body = "<p>Consulta mailer test: this is a diagnostic message.</p>"
    await send_email(
        subject=f"{subject_prefix}{SMTP_HOST}:{SMTP_PORT}",
        to=recipients,
        html=html_body,
        text="Test",
    )
    return await check_mailer()


def _safe_reply_to(value: str | None) -> str | None:
    v = (value or "").strip()
    if not v:
        return None
    _, addr = parseaddr(v)
    if not addr or "@" not in addr:
        return None
    if any(ch in addr for ch in ("\r", "\n", " ")):
        return None
    local, _, domain = addr.rpartition("@")
    if not local or "." not in domain:
        return None
    return addr


