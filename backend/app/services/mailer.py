    subject   = build_subject(payload)
    html_body = contact_html(payload)
    text_body = contact_text(payload)
    reply_to  = _safe_reply_to(payload.get("email"))  # <-- validate

    tos = NOTIFY_TO or ([SMTP_USER] if SMTP_USER else [])
