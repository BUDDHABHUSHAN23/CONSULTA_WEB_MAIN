# --- TLS selection ---
def _tls_kwargs(port: int) -> dict:
    # 465 => implicit TLS; 25/587 => STARTTLS; others => plain
    if port == 465:
        return {"use_tls": True}
    if port in (25, 587):
        return {"start_tls": True}
    return {}

def _normalize(addrs: Iterable[str]) -> Tuple[str, ...]:
    out, seen = [], set()
    for a in (addrs or []):
        a = (a or "").strip()
        if not a or "\n" in a or "\r" in a:
            continue
        k = a.lower()
        if k not in seen:
            out.append(a)
            seen.add(k)
    return tuple(out)

